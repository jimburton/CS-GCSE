# Python program to draw square 
# using Turtle Programming
import turtle
skk = turtle.Turtle()

# first side of house
skk.forward(50) # draw the line
skk.right(90) # turn 90 degrees

# second side of house
skk.forward(50)
skk.right(90)

# third side of house
skk.forward(50)
skk.right(90)

# fourth side of house
skk.forward(50)
skk.right(30)
    
# first side of roof
skk.forward(50)
skk.right(120)

# second side of roof
skk.forward(50)


turtle.done()